//! Config-sweep differential test: ArKan vs PyTorch reference across multiple training configs.
//!
//! Each config covers one dimension of the sweep:
//!   - Optimizer: SGD, Adam
//!   - Spline order: 3, 4
//!   - Loss: MSE, BCE-with-logits
//!   - Depth: single-hidden (2→8→1), multi-hidden (2→8→8→1)
//!   - Backend: CPU (all tests), GPU (gated #[ignore])
//!
//! HONESTY RULES (strictly enforced):
//!   - If Layer 1 fails → weight bridge or forward bug. STOP.
//!   - If Layer 2 fails → gradient bug. STOP.
//!   - If Layer 3 diverges → report step + localization. Do NOT loosen tolerances.
//!
//! Run CPU sweep:  cargo test --test reference_parity_sweep -- --nocapture
//! Run GPU tests:  cargo test --features gpu --test reference_parity_sweep -- --ignored --nocapture
//!
//! JSON files are generated by scripts/export_training_reference.py.

use arkan::loss::masked_bce_with_logits;
use arkan::optimizer::Optimizer;
use arkan::{Adam, AdamConfig, KanConfig, KanNetwork};
use serde::Deserialize;
use std::fs;
use std::path::Path;

// ---------------------------------------------------------------------------
// JSON schema — matches export_training_reference.py
// ---------------------------------------------------------------------------

#[derive(Deserialize, Debug)]
struct RefConfig {
    input_dim: usize,
    hidden_dims: Vec<usize>,
    output_dim: usize,
    grid_size: usize,
    spline_order: usize,
    grid_range: (f32, f32),
    #[allow(dead_code)]
    global_basis_size: usize,
    #[allow(dead_code)]
    dims: Vec<usize>,
}

#[derive(Deserialize, Debug)]
struct LayerWeights {
    weights: Vec<f32>,
    bias: Vec<f32>,
}

#[derive(Deserialize, Debug)]
struct Dataset {
    inputs: Vec<f32>,
    targets: Vec<f32>,
    n_samples: usize,
}

#[derive(Deserialize, Debug)]
struct OptimizerConfig {
    #[serde(rename = "type")]
    opt_type: String,
    lr: f32,
    // SGD fields (optional). Parsed so the struct mirrors the exported JSON
    // schema; the sweep only drives Adam today, so nothing reads it.
    #[allow(dead_code)]
    momentum: Option<f32>,
    // Adam fields (optional)
    beta1: Option<f32>,
    beta2: Option<f32>,
    epsilon: Option<f32>,
    weight_decay: Option<f32>,
}

#[derive(Deserialize, Debug)]
struct Reference {
    config: RefConfig,
    optimizer: OptimizerConfig,
    #[serde(default = "default_loss_type")]
    loss_type: String,
    dataset: Dataset,
    init_weights: Vec<LayerWeights>,
    step0_forward: Vec<f32>,
    step0_grads: Vec<LayerWeights>,
    loss_trajectory: Vec<f32>,
    final_weights: Vec<LayerWeights>,
}

fn default_loss_type() -> String {
    "mse".to_string()
}

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

fn load_reference(filename: &str) -> Reference {
    let manifest_dir = env!("CARGO_MANIFEST_DIR");
    let path = Path::new(manifest_dir)
        .join("tests")
        .join("reference_data")
        .join(filename);

    let data =
        fs::read_to_string(&path).unwrap_or_else(|e| panic!("Could not read {:?}: {}", path, e));

    serde_json::from_str(&data).unwrap_or_else(|e| panic!("Could not parse {}: {}", filename, e))
}

fn build_network_with_ref_weights(ref_data: &Reference) -> KanNetwork {
    let cfg = &ref_data.config;
    let config = KanConfig {
        input_dim: cfg.input_dim,
        output_dim: cfg.output_dim,
        hidden_dims: cfg.hidden_dims.clone(),
        grid_size: cfg.grid_size,
        spline_order: cfg.spline_order,
        grid_range: cfg.grid_range,
        input_mean: vec![0.0f32; cfg.input_dim],
        input_std: vec![1.0f32; cfg.input_dim],
        multithreading_threshold: 128,
        simd_width: 8,
        init_seed: None,
    };
    let mut network = KanNetwork::new(config);

    assert_eq!(
        network.layers.len(),
        ref_data.init_weights.len(),
        "Layer count mismatch"
    );

    for (layer_idx, ref_layer) in ref_data.init_weights.iter().enumerate() {
        let layer = &mut network.layers[layer_idx];
        assert_eq!(
            ref_layer.weights.len(),
            layer.weights.len(),
            "Layer {layer_idx} weight count mismatch"
        );
        assert_eq!(
            ref_layer.bias.len(),
            layer.bias.len(),
            "Layer {layer_idx} bias count mismatch"
        );
        layer.weights.copy_from_slice(&ref_layer.weights);
        layer.bias.copy_from_slice(&ref_layer.bias);
    }
    network
}

fn max_abs_err(a: &[f32], b: &[f32]) -> f32 {
    assert_eq!(a.len(), b.len());
    a.iter()
        .zip(b.iter())
        .map(|(x, y)| (x - y).abs())
        .fold(0.0f32, f32::max)
}

fn arkan_forward(network: &KanNetwork, dataset: &Dataset) -> Vec<f32> {
    let n = dataset.n_samples;
    let out_dim = network.config.output_dim;
    let mut workspace = network.create_workspace(n);
    let mut outputs = vec![0.0f32; n * out_dim];
    network.forward_batch(&dataset.inputs, &mut outputs, &mut workspace);
    outputs
}

/// Compute loss value and output gradient exactly matching ArKan's internals.
///
/// For MSE: grad[i] = 2*(pred-target)/N  (matches compute_masked_mse_loss_into)
/// For BCE: uses arkan::masked_bce_with_logits which matches PyTorch's
///          binary_cross_entropy_with_logits.
fn compute_loss_and_grad(predictions: &[f32], targets: &[f32], loss_type: &str) -> (f32, Vec<f32>) {
    match loss_type {
        "mse" => {
            let n = predictions.len() as f32;
            let mut loss = 0.0f32;
            let mut grad = vec![0.0f32; predictions.len()];
            for (i, (p, t)) in predictions.iter().zip(targets.iter()).enumerate() {
                let diff = p - t;
                loss += diff * diff;
                grad[i] = 2.0 * diff;
            }
            let inv = 1.0 / n;
            loss *= inv;
            for g in &mut grad {
                *g *= inv;
            }
            (loss, grad)
        }
        "bce" => masked_bce_with_logits(predictions, targets, None),
        _ => panic!("Unknown loss_type: {}", loss_type),
    }
}

/// Copy gradients only so the fixture comparison owns them independently of scratch.
fn run_backward(
    pass: arkan::training::ForwardPass<'_, '_>,
    grad_output: &[f32],
) -> (Vec<Vec<f32>>, Vec<Vec<f32>>) {
    let gradients = pass.backward(grad_output).unwrap();
    (gradients.weights.to_vec(), gradients.biases.to_vec())
}

