/// Asserts all 3 parity layers for a single config.
/// Returns (max_fwd_err, max_grad_err, max_traj_rel_err, pass).
/// On FAIL, panics with a diagnostic message.
fn assert_parity(config_name: &str, ref_data: &Reference) -> (f32, f32, f32) {
    let opt = &ref_data.optimizer;
    let loss_type = &ref_data.loss_type;
    println!(
        "\n=== [{config_name}] optimizer={}, order={}, loss={}, arch={:?} ===",
        opt.opt_type, ref_data.config.spline_order, loss_type, ref_data.config.dims
    );

    // -----------------------------------------------------------------------
    // LAYER 1: Forward parity
    // -----------------------------------------------------------------------
    let network = build_network_with_ref_weights(ref_data);
    let arkan_out = arkan_forward(&network, &ref_data.dataset);
    let max_fwd_err = max_abs_err(&arkan_out, &ref_data.step0_forward);
    println!(
        "[{config_name}][L1] Forward parity: max_abs_err = {:.2e}  (tol 1e-5)",
        max_fwd_err
    );

    assert!(
        max_fwd_err < 1e-5,
        "[{config_name}][L1 FAIL] Forward parity failed: max_err={:.4e} > 1e-5\n\
         Weight bridge or forward-pass bug.\n\
         ArKan[:5]  = {:?}\n\
         PyTorch[:5] = {:?}",
        max_fwd_err,
        &arkan_out[..arkan_out.len().min(5)],
        &ref_data.step0_forward[..ref_data.step0_forward.len().min(5)],
    );
    println!("[{config_name}][L1] PASS");

    // -----------------------------------------------------------------------
    // LAYER 2: Gradient parity
    // -----------------------------------------------------------------------
    let network = build_network_with_ref_weights(ref_data);
    let n = ref_data.dataset.n_samples;
    let out_dim = network.config.output_dim;
    let mut workspace = network.create_workspace(n);

    let mut predictions = vec![0.0f32; n * out_dim];
    let pass = network
        .try_forward_for_backward(&ref_data.dataset.inputs, &mut predictions, &mut workspace)
        .unwrap();

    let (_, grad_output) =
        compute_loss_and_grad(&predictions, &ref_data.dataset.targets, loss_type);

    let (weight_grads, bias_grads) = run_backward(pass, &grad_output);

    let grad_tol = 1e-4f32;
    let mut max_w_err = 0.0f32;
    let mut max_b_err = 0.0f32;
    let mut all_pass = true;

    for (layer_idx, ref_grad) in ref_data.step0_grads.iter().enumerate() {
        let w_err = max_abs_err(&weight_grads[layer_idx], &ref_grad.weights);
        let b_err = max_abs_err(&bias_grads[layer_idx], &ref_grad.bias);
        max_w_err = max_w_err.max(w_err);
        max_b_err = max_b_err.max(b_err);
        println!(
            "[{config_name}][L2] Layer {layer_idx}: weight_grad err={:.2e}, bias_grad err={:.2e}",
            w_err, b_err
        );
        if w_err >= grad_tol || b_err >= grad_tol {
            eprintln!(
                "[{config_name}][L2 FAIL] Layer {layer_idx}: w_err={:.4e}, b_err={:.4e} >= tol {:.1e}",
                w_err, b_err, grad_tol
            );
            all_pass = false;
        }
    }

    let max_grad_err = max_w_err.max(max_b_err);
    println!(
        "[{config_name}][L2] Gradient parity: max_w_err={:.2e}, max_b_err={:.2e}  (tol 1e-4)",
        max_w_err, max_b_err
    );
    assert!(
        all_pass,
        "[{config_name}][L2 FAIL] Gradient parity failed. \
         Forward (L1) passed, so error is in gradient computation."
    );
    println!("[{config_name}][L2] PASS");

    // -----------------------------------------------------------------------
    // LAYER 3: Trajectory parity
    // -----------------------------------------------------------------------
    let mut network = build_network_with_ref_weights(ref_data);
    let n_steps = ref_data.loss_trajectory.len();
    let lr = opt.lr;
    let mut workspace = network.create_workspace(n);

    // Build optimizer state for Adam (SGD uses train_step directly)
    let mut adam_opt: Option<Adam> = match opt.opt_type.as_str() {
        "adam" => {
            let cfg = AdamConfig {
                lr,
                beta1: opt.beta1.unwrap_or(0.9),
                beta2: opt.beta2.unwrap_or(0.999),
                epsilon: opt.epsilon.unwrap_or(1e-8),
                weight_decay: opt.weight_decay.unwrap_or(0.0),
                ..AdamConfig::default()
            };
            Some(Adam::new(&network, cfg))
        }
        _ => None,
    };

    let rel_tol = 1e-3f32;
    let mut diverged_at: Option<usize> = None;
    let mut max_traj_rel_err = 0.0f32;

    for step in 0..n_steps {
        let arkan_loss = match opt.opt_type.as_str() {
            "sgd" => {
                // SGD+MSE: use train_step directly (handles backward + SGD update)
                if loss_type == "mse" {
                    network.train_step(
                        &ref_data.dataset.inputs,
                        &ref_data.dataset.targets,
                        None,
                        lr,
                        &mut workspace,
                    )
                } else {
                    // SGD+BCE: manual forward + BCE loss + backward + SGD update
                    let mut predictions = vec![0.0f32; n * out_dim];
                    let pass = network
                        .try_forward_for_backward(
                            &ref_data.dataset.inputs,
                            &mut predictions,
                            &mut workspace,
                        )
                        .unwrap();
                    let (loss, grad_out) =
                        compute_loss_and_grad(&predictions, &ref_data.dataset.targets, loss_type);
                    let (wg, bg) = run_backward(pass, &grad_out);
                    // SGD update: w -= lr * grad
                    for (layer_idx, layer) in network.layers.iter_mut().enumerate() {
                        for (w, g) in layer.weights.iter_mut().zip(wg[layer_idx].iter()) {
                            *w -= lr * g;
                        }
                        for (b, g) in layer.bias.iter_mut().zip(bg[layer_idx].iter()) {
                            *b -= lr * g;
                        }
                    }
                    loss
                }
            }
            "adam" => {
                // Adam: manual forward + loss + backward + Adam update
                let mut predictions = vec![0.0f32; n * out_dim];
                let pass = network
                    .try_forward_for_backward(
                        &ref_data.dataset.inputs,
                        &mut predictions,
                        &mut workspace,
                    )
                    .unwrap();
                let (loss, grad_out) =
                    compute_loss_and_grad(&predictions, &ref_data.dataset.targets, loss_type);
                let (wg, bg) = run_backward(pass, &grad_out);
                // Adam update
                adam_opt
                    .as_mut()
                    .unwrap()
                    .step(&mut network, &wg, &bg, None)
                    .unwrap();
                loss
            }
            other => panic!("[{config_name}] Unknown optimizer type: {other}"),
        };

        let ref_loss = ref_data.loss_trajectory[step];
        let rel_err = (arkan_loss - ref_loss).abs() / ref_loss.abs().max(1e-8);
        max_traj_rel_err = max_traj_rel_err.max(rel_err);

        if step < 5 || step % 10 == 0 {
            println!(
                "[{config_name}][L3] step {:3}: arkan={:.6}, ref={:.6}, rel_err={:.2e}",
                step, arkan_loss, ref_loss, rel_err
            );
        }

        if rel_err >= rel_tol && diverged_at.is_none() {
            diverged_at = Some(step);
            eprintln!(
                "[{config_name}][L3] DIVERGENCE at step {}: arkan={:.6}, ref={:.6}, rel_err={:.4e}",
                step, arkan_loss, ref_loss, rel_err
            );
        }
    }

    if let Some(div_step) = diverged_at {
        // Localization: compare final weights
        let mut max_w_diff = 0.0f32;
        for (li, ref_final) in ref_data.final_weights.iter().enumerate() {
            let w_err = max_abs_err(&network.layers[li].weights, &ref_final.weights);
            let b_err = max_abs_err(&network.layers[li].bias, &ref_final.bias);
            max_w_diff = max_w_diff.max(w_err).max(b_err);
            println!(
                "[{config_name}][L3] Final weight diff layer {li}: w={:.4e}, b={:.4e}",
                w_err, b_err
            );
        }
        panic!(
            "[{config_name}][L3 FAIL] Training trajectory diverged at step {}.\n\
             L1 (forward) and L2 (gradient) PASSED, so:\n\
             SUSPECT: optimizer update formula or loss gradient mismatch.\n\
             Config: optimizer={}, loss={}, spline_order={}.\n\
             max_traj_rel_err={:.4e}, max_final_weight_diff={:.4e}",
            div_step,
            opt.opt_type,
            loss_type,
            ref_data.config.spline_order,
            max_traj_rel_err,
            max_w_diff
        );
    }

    // Final weight comparison
    let w_tol = 1e-3f32;
    let mut max_final_err = 0.0f32;
    for (li, ref_final) in ref_data.final_weights.iter().enumerate() {
        let w_err = max_abs_err(&network.layers[li].weights, &ref_final.weights);
        let b_err = max_abs_err(&network.layers[li].bias, &ref_final.bias);
        max_final_err = max_final_err.max(w_err).max(b_err);
        println!(
            "[{config_name}][L3] Final weight diff layer {li}: w={:.4e}, b={:.4e}",
            w_err, b_err
        );
    }

    println!(
        "[{config_name}][L3] Trajectory PASS: max_traj_rel_err={:.2e}, max_final_weight_err={:.4e}",
        max_traj_rel_err, max_final_err
    );
    assert!(
        max_final_err < w_tol,
        "[{config_name}][L3 FAIL] Final weights diverged: max_err={:.4e} > {:.1e}",
        max_final_err,
        w_tol
    );
    println!("[{config_name}] ALL LAYERS PASS");

    (max_fwd_err, max_grad_err, max_traj_rel_err)
}

