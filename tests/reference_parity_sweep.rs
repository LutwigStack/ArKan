/// GPU parity: build GpuNetwork from CPU reference weights, train via hybrid path
/// (GPU forward + CPU backward + CPU Adam + weight sync), compare to PyTorch CPU oracle.
///
/// Note: GpuNetwork::train_step_mse uses the hybrid approach with CPU Adam optimizer.
/// It no longer clips gradients by default (the previously hardcoded
/// max_grad_norm=Some(1.0) was removed; default is now None, matching the CPU path
/// and the unclipped PyTorch oracle). We use the Adam reference (same JSON) since the
/// GPU hybrid path uses Adam.
#[cfg(feature = "gpu")]
#[test]
#[ignore = "Requires GPU"]
fn sweep_gpu_adam_hybrid() {
    use arkan::gpu::{GpuNetwork, WgpuBackend, WgpuOptions};
    use arkan::{Adam, AdamConfig};

    // Use the Adam reference — GPU train_step_mse uses CPU Adam internally and
    // (since the hardcoded clip was removed) no longer clips gradients by default,
    // so it should track the unclipped PyTorch Adam oracle exactly.
    let ref_data = load_reference("training_ref_adam_order3.json");
    let config_name = "gpu_adam_hybrid";
    let opt = &ref_data.optimizer;
    let lr = opt.lr;

    println!(
        "\n=== [{config_name}] GPU hybrid (forward GPU + backward CPU Adam) order={} ===",
        ref_data.config.spline_order
    );

    let backend = WgpuBackend::init(WgpuOptions::default()).expect("Failed to create GPU backend");

    let cpu_network_init = build_network_with_ref_weights(&ref_data);

    // --- L1: GPU forward parity ---
    {
        let mut gpu_net =
            GpuNetwork::from_cpu(&backend, &cpu_network_init).expect("GpuNetwork::from_cpu failed");
        let n = ref_data.dataset.n_samples;
        let mut gpu_ws = gpu_net
            .create_workspace(n)
            .expect("create_workspace failed");
        let gpu_out = gpu_net
            .forward_batch(&ref_data.dataset.inputs, n, &mut gpu_ws)
            .expect("GPU forward failed");

        let fwd_err = max_abs_err(&gpu_out, &ref_data.step0_forward);
        println!(
            "[{config_name}][L1] GPU forward parity: max_err={:.2e}  (tol 1e-4)",
            fwd_err
        );
        assert!(
            fwd_err < 1e-4,
            "[{config_name}][L1 FAIL] GPU forward error {:.4e} > 1e-4\n\
             GPU forward path or GpuNetwork::from_cpu weight bridge is broken.",
            fwd_err
        );
        println!("[{config_name}][L1] PASS");
    }

    // --- L3: GPU hybrid Adam trajectory vs CPU PyTorch Adam oracle ---
    // IMPORTANT: train_step_mse applies max_grad_norm=Some(1.0) internally.
    // Our PyTorch oracle uses no clipping. To make a fair comparison, we test
    // whether the trajectories match the oracle — if they diverge, we report
    // the likely cause (the hardcoded clipping in train_step_mse).
    let n_steps = ref_data.loss_trajectory.len();
    let n = ref_data.dataset.n_samples;

    let mut gpu_net =
        GpuNetwork::from_cpu(&backend, &cpu_network_init).expect("GpuNetwork::from_cpu failed");
    let mut gpu_ws = gpu_net
        .create_workspace(n)
        .expect("create_workspace failed");
    let mut cpu_net_for_gpu = build_network_with_ref_weights(&ref_data);

    let adam_cfg = AdamConfig {
        lr,
        beta1: opt.beta1.unwrap_or(0.9),
        beta2: opt.beta2.unwrap_or(0.999),
        epsilon: opt.epsilon.unwrap_or(1e-8),
        weight_decay: opt.weight_decay.unwrap_or(0.0),
        ..AdamConfig::default()
    };
    let mut adam_cpu = Adam::new(&cpu_net_for_gpu, adam_cfg);

    // NOTE: train_step_mse applies Some(1.0) gradient clipping.
    // This differs from PyTorch oracle (no clipping), so trajectory MAY diverge.
    // We use rel_tol=5e-3 to check if clipping is actually impactful on this dataset.
    let rel_tol = 5e-3f32;
    let mut diverged_at: Option<usize> = None;
    let mut max_traj_rel_err = 0.0f32;

    for step in 0..n_steps {
        let arkan_loss = gpu_net
            .train_step_mse(
                &ref_data.dataset.inputs,
                &ref_data.dataset.targets,
                n,
                &mut gpu_ws,
                &mut adam_cpu,
                &mut cpu_net_for_gpu,
            )
            .expect("GPU hybrid Adam train_step_mse failed");

        let ref_loss = ref_data.loss_trajectory[step];
        let rel_err = (arkan_loss - ref_loss).abs() / ref_loss.abs().max(1e-8);
        max_traj_rel_err = max_traj_rel_err.max(rel_err);

        if step < 5 || step % 10 == 0 {
            println!(
                "[{config_name}][L3] step {:3}: gpu={:.6}, ref={:.6}, rel_err={:.2e}",
                step, arkan_loss, ref_loss, rel_err
            );
        }

        if rel_err >= rel_tol && diverged_at.is_none() {
            diverged_at = Some(step);
            eprintln!(
                "[{config_name}][L3] GPU DIVERGENCE at step {}: gpu={:.6}, ref={:.6}, rel_err={:.4e}",
                step, arkan_loss, ref_loss, rel_err
            );
        }
    }

    if let Some(div_step) = diverged_at {
        panic!(
            "[{config_name}][L3 FAIL] GPU hybrid Adam trajectory diverged at step {}.\n\
             train_step_mse no longer clips by default, so the GPU hybrid path should\n\
             match the unclipped PyTorch Adam oracle. A divergence here indicates a real\n\
             GPU training bug (forward/backward/optimizer), not gradient clipping.\n\
             max_traj_rel_err={:.4e} > {:.1e}",
            div_step, max_traj_rel_err, rel_tol
        );
    }

    println!(
        "[{config_name}][L3] GPU hybrid Adam Trajectory PASS: max_traj_rel_err={:.2e}",
        max_traj_rel_err
    );
    println!("[{config_name}] GPU hybrid ALL LAYERS PASS");
}
